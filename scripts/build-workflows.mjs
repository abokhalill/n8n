// Code nodes cannot import local files, so the shared logic has to be inlined into
// each one. Hand-copying it would drift the moment 09_Lib changes, which is not 
// what we want.
//
//   node scripts/build-workflows.mjs          inject the current library
//   node scripts/build-workflows.mjs --check  fail if any workflow is stale

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const LIB_DIR = join(ROOT, '09_Lib');
const WF_DIR = join(ROOT, '02_Workflows');

const START = '/* __LEADOPS_LIB__ */';
const END = '/* __END_LEADOPS_LIB__ */';

// Dependency order. Everything is flattened into one scope, so a file may only
// reference names defined above it.
const LIB_FILES = ['hash.mjs', 'ids.mjs', 'normalize.mjs', 'idempotency.mjs', 'csv.mjs', 'validate.mjs', 'scoring.mjs', 'dedup.mjs', 'routing.mjs', 'odoo.mjs', 'followup.mjs'];

function bundle() {
  const parts = LIB_FILES.map((file) => {
    const src = readFileSync(join(LIB_DIR, file), 'utf8')
      .split('\n')
      .filter((line) => !/^\s*import\s.+from\s+['"]\./.test(line))
      .filter((line) => !/^\s*export\s*\{[^}]*\}\s*;?\s*$/.test(line))
      .map((line) => line.replace(/^(\s*)export\s+(function|const|let|class|async)\b/, '$1$2'))
      .join('\n')
      .trim();
    return `// ---- 09_Lib/${file} ${'-'.repeat(Math.max(0, 60 - file.length))}\n${src}`;
  });

  return [
    START,
    '// Generated by scripts/build-workflows.mjs from 09_Lib. Do not edit here —',
    '// edit the library, which is unit tested, then re-run the build.',
    ...parts,
    END,
  ].join('\n');
}

function injectInto(jsCode, lib) {
  const start = jsCode.indexOf(START);
  const end = jsCode.indexOf(END);
  if (start === -1 || end === -1) return null;      // node opts out of the library
  return lib + jsCode.slice(end + END.length);
}

const check = process.argv.includes('--check');
const lib = bundle();
let touched = 0, stale = [];

const files = readdirSync(WF_DIR).filter((f) => f.endsWith('.json')).sort();
if (!files.length) { console.log('no workflows in 02_Workflows yet'); process.exit(0); }

for (const file of files) {
  const path = join(WF_DIR, file);
  const original = readFileSync(path, 'utf8');
  const wf = JSON.parse(original);
  let changed = false;

  for (const node of wf.nodes ?? []) {
    const code = node.parameters?.jsCode;
    if (typeof code !== 'string') continue;
    const next = injectInto(code, lib);
    if (next !== null && next !== code) { node.parameters.jsCode = next; changed = true; }
  }

  // Every workflow routes unhandled failures to the error handler. Wiring it here
  // rather than in each generator means a new workflow cannot forget to.
  const ERROR_WF = 'wf50errorhandler';
  if (wf.id !== ERROR_WF) {
    wf.settings ??= {};
    if (wf.settings.errorWorkflow !== ERROR_WF) { wf.settings.errorWorkflow = ERROR_WF; changed = true; }
  }

  if (!changed) continue;
  if (check) { stale.push(file); continue; }
  writeFileSync(path, JSON.stringify(wf, null, 2) + '\n');
  touched++;
  console.log(`  updated ${file}`);
}

if (check) {
  if (stale.length) {
    console.error(`stale workflows (run: node scripts/build-workflows.mjs):\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`all ${files.length} workflows carry the current library`);
} else {
  console.log(touched ? `injected library into ${touched} workflow(s)` : 'all workflows already current');
}
